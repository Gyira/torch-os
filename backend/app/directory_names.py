OLD_ROOTS = ("00_人生路", "01_自我档案", "02_生活运营", "03_知识库")
ROOTS = tuple(NUMBERED_NAMES[key] for key in OLD_ROOTS)

def canonical_path(value: str) -> str:
    parts = str(value).replace("\\", "/").split("/")
    if not parts or parts[0] not in (*OLD_ROOTS, *ROOTS):
        return str(value)
    return "/".join(NUMBERED_NAMES.get(part, part) for part in parts)
